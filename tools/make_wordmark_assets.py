#!/usr/bin/env python3
"""Make placeholder brand assets from a word (e.g. "Scout") when no logo files exist yet.

Usage:
    python3 tools/make_wordmark_assets.py customers/<key>/customer.yml [--font PATH.ttf]

Writes into customers/<key>/assets/:
    logo.svg                          square logo (rounded square, word, dot) used in the app
    android/launcher_<icon>.xml       adaptive launcher icon (background + foreground + monochrome)
    android/launcher_<icon>_background.xml
    android/launcher_<icon>_foreground.xml
    android/launcher_<icon>_monochrome.xml
    android/<icon>_vector.xml         splash screen drawable
    android/notification_icon.xml     small white status-bar icon (first letter)

The word is converted to vector outlines, so no font is needed at build time.
Default font: Liberation Sans Bold (metric-compatible with Arial, freely licensed).
Replace these files with the client's real logo assets when they arrive.
"""
import argparse
import os
import sys

import yaml
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

DEFAULT_FONT = "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"


def word_path(font, text, x, baseline, height):
    """SVG path data for `text`, cap height = `height` units, starting at x, sitting on `baseline`."""
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm
    cap = getattr(font["OS/2"], "sCapHeight", 0) or int(upm * 0.716)
    s = height / cap
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    cursor = 0.0
    for ch in text:
        g = cmap[ord(ch)]
        tp = TransformPen(pen, (s, 0, 0, -s, x + cursor * s, baseline))
        gs[g].draw(tp)
        cursor += font["hmtx"][g][0]
    return pen.getCommands(), cursor * s


def rounded_square(x, y, size, r):
    k = 0.5523 * r  # cubic approximation of a quarter circle
    x2, y2 = x + size, y + size
    return (f"M{x + r},{y} L{x2 - r},{y} C{x2 - r + k},{y} {x2},{y + r - k} {x2},{y + r} "
            f"L{x2},{y2 - r} C{x2},{y2 - r + k} {x2 - r + k},{y2} {x2 - r},{y2} "
            f"L{x + r},{y2} C{x + r - k},{y2} {x},{y2 - r + k} {x},{y2 - r} "
            f"L{x},{y + r} C{x},{y + r - k} {x + r - k},{y} {x + r},{y} Z")


def circle(cx, cy, r):
    k = 0.5523 * r
    return (f"M{cx},{cy - r} C{cx + k},{cy - r} {cx + r},{cy - k} {cx + r},{cy} "
            f"C{cx + r},{cy + k} {cx + k},{cy + r} {cx},{cy + r} "
            f"C{cx - k},{cy + r} {cx - r},{cy + k} {cx - r},{cy} "
            f"C{cx - r},{cy - k} {cx - k},{cy - r} {cx},{cy - r} Z")


def layout(font, text, canvas, width_frac):
    """Word + dot centred in a square canvas; returns (word path, dot path)."""
    target_w = canvas * width_frac
    # measure at unit height first
    _, w1 = word_path(font, text, 0, 0, 1.0)
    gap, dot_r = 0.12, 0.13          # in cap-height units
    total_per_cap = w1 + gap + 2 * dot_r
    h = target_w / total_per_cap
    x0 = (canvas - target_w) / 2
    baseline = canvas / 2 + h / 2
    d_word, w = word_path(font, text, x0, baseline, h)
    d_dot = circle(round(x0 + w + gap * h + dot_r * h, 2), round(baseline - dot_r * h, 2), round(dot_r * h, 2))
    return d_word, d_dot


def vector_xml(paths, size_dp=108, viewport=108):
    body = "\n".join(f'    <path android:fillColor="{c}" android:pathData="{d}" />' for c, d in paths)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by tools/make_wordmark_assets.py (placeholder logo) -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n{body}\n</vector>\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("config")
    ap.add_argument("--font", default=DEFAULT_FONT)
    a = ap.parse_args()

    cfg = yaml.safe_load(open(a.config, encoding="utf-8"))
    text, icon = cfg["app"]["name"], cfg["app"]["icon"]
    primary = cfg["look"]["primary"]
    straw = cfg["look"]["accent_dark_theme"]
    dot = cfg["look"]["highlight"]
    font = TTFont(a.font)
    out = os.path.join(os.path.dirname(os.path.abspath(a.config)), "assets")
    andr = os.path.join(out, "android")
    os.makedirs(andr, exist_ok=True)

    # 1. square logo (512 units): rounded indigo square, straw word, terracotta dot
    w, d = layout(font, text, 512, 0.74)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">\n'
           f'  <!-- Placeholder logo generated by tools/make_wordmark_assets.py -->\n'
           f'  <path fill="{primary}" d="{rounded_square(0, 0, 512, 104)}"/>\n'
           f'  <path fill="{straw}" d="{w}"/>\n'
           f'  <path fill="{dot}" d="{d}"/>\n</svg>\n')
    open(os.path.join(out, "logo.svg"), "w", encoding="utf-8").write(svg)

    # 2. adaptive launcher icon: 108 x 108 canvas, content inside the 66-unit safe zone
    w, d = layout(font, text, 108, 0.56)
    files = {
        f"launcher_{icon}.xml": (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <background android:drawable="@drawable/launcher_{icon}_background" />\n'
            f'    <foreground android:drawable="@drawable/launcher_{icon}_foreground" />\n'
            f'    <monochrome android:drawable="@drawable/launcher_{icon}_monochrome" />\n'
            '</adaptive-icon>\n'),
        f"launcher_{icon}_background.xml": vector_xml([(primary, "M0,0h108v108h-108z")]),
        f"launcher_{icon}_foreground.xml": vector_xml([(straw, w), (dot, d)]),
        f"launcher_{icon}_monochrome.xml": vector_xml([("#FFFFFF", w), ("#FFFFFF", d)]),
    }
    # 3. splash drawable: the square logo as a vector (192 dp in splash.xml)
    w2, d2 = layout(font, text, 108, 0.74)
    files[f"{icon}_vector.xml"] = vector_xml([(primary, rounded_square(0, 0, 108, 22)), (straw, w2), (dot, d2)])
    # 4. status-bar notification icon: first letter, white, 24 x 24
    letter = text[0]
    _, lw = word_path(font, letter, 0, 0, 1.0)
    h = 17.0
    d_letter, _ = word_path(font, letter, (24 - lw * h) / 2, 12 + h / 2, h)
    files["notification_icon.xml"] = vector_xml([("#FFFFFF", d_letter)], size_dp=24, viewport=24)
    for name, content in files.items():
        open(os.path.join(andr, name), "w", encoding="utf-8").write(content)
    print(f"Wrote {out}/logo.svg and {len(files)} Android drawables for '{text}'")


if __name__ == "__main__":
    sys.exit(main())
